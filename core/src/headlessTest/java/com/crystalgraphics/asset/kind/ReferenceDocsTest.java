package com.crystalgraphics.asset.kind;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertTrue;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayDeque;
import java.util.Deque;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;

import org.junit.Test;

import com.crystalgraphics.net.object.CgNetField;
import com.crystalgraphics.object.CgProperty;
import com.crystalgraphics.object.CgType;
import com.crystalgraphics.object.CgValueType;
import com.crystalgraphics.world.CgEntityProperties;

/**
 * The user docs' reference tables, generated from the declarations so they cannot drift: every animation file kind's
 * keys, every anim graph node kind's fields, and the entity motion fields. A table that differs fails, naming the page;
 * {@code -PupdateDocs=true} writes it.
 */
public class ReferenceDocsTest {

    private static final Path DOCS = Paths.get("..", "docs");
    private static final boolean UPDATE = Boolean.getBoolean("crystalgraphics.docs.update");

    @Test
    public void assetKeysTableIsCurrent() throws IOException {
        CgAssetKinds.register();
        StringBuilder out = new StringBuilder();
        out.append("# Reference: animation files\n\n")
           .append("Every key of every animation file, from the engine's own declarations. How to use each kind is its guide:\n")
           .append("[`../README.md`](../README.md). A struct a key holds is listed once, below the kind that first uses it.\n\n")
           .append("<!-- generated by ReferenceDocsTest: -PupdateDocs=true rewrites it -->\n");
        Set<CgType> seen = new LinkedHashSet<>();
        for (CgType kind : List.of(CgBodyKinds.CLIP, CgBodyKinds.SKELETON, CgBodyKinds.ANIM_GRAPH, CgBodyKinds.BLEND_SPACE,
                CgBodyKinds.SPRINGS, CgBodyKinds.RIG, CgBodyKinds.RETARGETER, CgBodyKinds.ACTOR)) {
            out.append("\n## `").append(kind.folder()).append("/`: ").append(kind.id()).append("\n\n");
            table(kind, out);
            structsUnder(kind, seen, out);
        }
        check("animation/reference/assets.md", out.toString());
    }

    @Test
    public void nodeTableIsCurrent() throws IOException {
        CgAssetKinds.register();
        StringBuilder out = new StringBuilder();
        out.append("# Reference: anim graph nodes\n\n")
           .append("Every node `kind` an `anim_graph` file takes, and its fields, from the engine's own declarations. What each\n")
           .append("node does: [`../guides/graphs-and-variables.md`](../guides/graphs-and-variables.md) § *The nodes*.\n\n")
           .append("<!-- generated by ReferenceDocsTest: -PupdateDocs=true rewrites it -->\n");
        Map<String, CgType> nodes = new TreeMap<>(CgBodyKinds.ANIM_NODES.members());
        Set<CgType> seen = new LinkedHashSet<>();
        for (Map.Entry<String, CgType> e : nodes.entrySet()) {
            out.append("\n## `").append(e.getKey()).append("`\n\n");
            table(e.getValue(), out);
            structsUnder(e.getValue(), seen, out);
        }
        check("animation/reference/nodes.md", out.toString());
    }

    /** The hand-written motion table names every field of the motion type, by its graph name and kind, and no other. */
    @Test
    public void motionTableNamesEveryField() throws IOException {
        String page = new String(Files.readAllBytes(DOCS.resolve("entities/reference/motion.md")), StandardCharsets.UTF_8);
        int rows = 0;
        for (CgNetField<?> f : CgEntityProperties.MOTION.fields()) {
            String kind = f.kind() == CgNetField.Kind.BOOL ? "bool" : f.kind() == CgNetField.Kind.INT ? "int" : "float";
            assertTrue("motion.md lacks entity." + f.name(), page.contains("`" + f.name() + "`"));
            assertTrue("motion.md gives entity." + f.name() + " another kind than " + kind,
                    page.matches("(?s).*`" + f.name() + "`[^\\n]*\\| " + kind + " \\|.*"));
            rows++;
        }
        assertEquals(54, rows);
    }

    private static void table(CgType type, StringBuilder out) {
        if (type.properties().isEmpty()) {
            out.append("No fields of its own.\n");
            return;
        }
        out.append("| Key | Type | Default | Required |\n|---|---|---|---|\n");
        for (CgProperty p : type.properties()) {
            out.append("| `").append(p.name()).append("` | ").append(describe(p.type())).append(" | ")
               .append(p.defaultValue() == null ? "" : "`" + p.defaultValue() + "`").append(" | ")
               .append(p.required() ? "yes" : "").append(" |\n");
        }
    }

    /** Every struct reached from {@code type}'s keys, each once, as a table of its own. */
    private static void structsUnder(CgType type, Set<CgType> seen, StringBuilder out) {
        Deque<CgType> todo = new ArrayDeque<>();
        for (CgProperty p : type.properties()) structOf(p.type(), todo);
        while (!todo.isEmpty()) {
            CgType s = todo.poll();
            if (!seen.add(s)) continue;
            out.append("\n### `").append(s.id()).append("`\n\n");
            table(s, out);
            for (CgProperty p : s.properties()) structOf(p.type(), todo);
        }
    }

    private static void structOf(CgValueType t, Deque<CgType> todo) {
        if (t == null) return;
        switch (t.kind()) {
            case STRUCT, ID_LIST -> { if (t.type() != null) todo.add(t.type()); }
            case LIST, MAP -> structOf(t.element(), todo);
            default -> { }
        }
    }

    private static String describe(CgValueType t) {
        return "`" + t.toString().replace("|", "\\|") + "`";
    }

    private static void check(String page, String generated) throws IOException {
        Path file = DOCS.resolve(page);
        if (UPDATE) {
            Files.createDirectories(file.getParent());
            Files.write(file, generated.getBytes(StandardCharsets.UTF_8));
            return;
        }
        String now = Files.exists(file) ? new String(Files.readAllBytes(file), StandardCharsets.UTF_8).replace("\r\n", "\n") : "";
        assertEquals(page + " is not what the declarations say: run with -PupdateDocs=true", generated, now);
    }
}
