package com.crystalgraphics.variable;

import com.crystalgraphics.vfx.CgVfxSystem;
import org.junit.Test;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.net.URISyntaxException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.Enumeration;
import java.util.List;
import java.util.jar.JarEntry;
import java.util.jar.JarFile;
import java.util.stream.Stream;

import static org.junit.Assert.assertTrue;
import static org.junit.Assert.fail;

/**
 * {@code docs/DEBUG_FLAGS.md} below its marker is the registry: every engine variable that is not a player's setting,
 * by area. Each class of core and platform naming {@link CgVar} is initialised, so its variables are declared, and the
 * section is rendered from {@link CgVars#all()}. On a difference the file is rewritten and the test fails: review the
 * diff and commit it.
 */
public class DebugFlagsDocTest {

    static final String MARKER = "<!-- Generated by DebugFlagsDocTest from the variable registry: edit the declarations, not below. -->";
    private static final byte[] NEEDLE = "com/crystalgraphics/variable/CgVar".getBytes(StandardCharsets.US_ASCII);
    private static final String PREFIX = "crystalgraphics.";

    @Test
    public void theDocListsEveryVariable() throws IOException {
        List<String> failed = new ArrayList<>();
        for (Path root : new Path[]{rootOf(CgVar.class), rootOf(CgVfxSystem.class)}) declareAll(root, failed);
        assertTrue("classes declaring variables failed to initialise, so their variables are missing: " + failed,
                failed.isEmpty());

        Path doc = findDoc();
        String text = new String(Files.readAllBytes(doc), StandardCharsets.UTF_8);
        int at = text.indexOf(MARKER);
        assertTrue(doc + " has lost its marker line: " + MARKER, at >= 0);
        String head = text.substring(0, at + MARKER.length());
        String nl = text.contains("\r\n") ? "\r\n" : "\n";
        String expected = head + nl + render().replace("\n", nl);
        if (!expected.equals(text)) {
            Files.write(doc, expected.getBytes(StandardCharsets.UTF_8));
            fail("regenerated " + doc + " from the variable registry: review the diff and commit it");
        }
    }

    static String render() {
        StringBuilder out = new StringBuilder();
        String area = null;
        for (CgVar<?> v : CgVars.under(PREFIX)) {
            if (v.has(CgVar.SAVED)) continue;
            String rest = v.id().substring(PREFIX.length());
            String next = rest.contains(".") ? rest.substring(0, rest.indexOf('.')) : rest;
            if (!next.equals(area)) {
                area = next;
                out.append('\n').append("## `").append(PREFIX).append(area).append("`\n\n");
                out.append("| Variable | Takes | Default | |\n|---|---|---|---|\n");
            }
            out.append("| `").append(v.id()).append("` | ").append(takes(v)).append(" | ")
                    .append(v.defaultText().isEmpty() ? "empty" : "`" + cell(v.defaultText()) + "`").append(" | ")
                    .append(cell(v.description()));
            if (v.has(CgVar.RESTART)) out.append(" Read at launch.");
            if (v.has(CgVar.READ_ONLY)) out.append(" Not from the console.");
            out.append(" |\n");
        }
        return out.toString();
    }

    private static String takes(CgVar<?> v) {
        switch (v.type()) {
            case "bool": return "true, false";
            case "text": return "text";
            default: return cell(v.range());
        }
    }

    private static String cell(String s) {
        return s.replace("|", "\\|");
    }

    // ── finding the declarations ───────────────────────────────────────────────

    private static void declareAll(Path root, List<String> failed) throws IOException {
        if (Files.isDirectory(root)) {
            try (Stream<Path> files = Files.walk(root)) {
                for (Path file : (Iterable<Path>) files.filter(p -> p.toString().endsWith(".class"))::iterator) {
                    if (names(Files.readAllBytes(file))) declare(root.relativize(file).toString(), failed);
                }
            }
            return;
        }
        try (JarFile jar = new JarFile(root.toFile())) {
            Enumeration<JarEntry> entries = jar.entries();
            while (entries.hasMoreElements()) {
                JarEntry entry = entries.nextElement();
                if (!entry.getName().endsWith(".class") || entry.getName().startsWith("META-INF")) continue;
                try (InputStream in = jar.getInputStream(entry)) {
                    if (names(readAll(in))) declare(entry.getName(), failed);
                }
            }
        }
    }

    private static void declare(String path, List<String> failed) {
        String name = path.replace('\\', '/').replace('/', '.').substring(0, path.length() - ".class".length());
        if (name.startsWith("com.crystalgraphics.variable.")) return;
        try {
            Class.forName(name, true, DebugFlagsDocTest.class.getClassLoader());
        } catch (Throwable t) {
            failed.add(name + " (" + (t.getCause() != null ? t.getCause() : t) + ")");
        }
    }

    private static boolean names(byte[] bytes) {
        outer:
        for (int i = 0; i <= bytes.length - NEEDLE.length; i++) {
            for (int j = 0; j < NEEDLE.length; j++) {
                if (bytes[i + j] != NEEDLE[j]) continue outer;
            }
            return true;
        }
        return false;
    }

    private static byte[] readAll(InputStream in) throws IOException {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        byte[] buffer = new byte[8192];
        for (int n; (n = in.read(buffer)) > 0; ) out.write(buffer, 0, n);
        return out.toByteArray();
    }

    private static Path rootOf(Class<?> type) {
        try {
            return Paths.get(type.getProtectionDomain().getCodeSource().getLocation().toURI());
        } catch (URISyntaxException e) {
            throw new IllegalStateException(e);
        }
    }

    /** {@code docs/DEBUG_FLAGS.md} in the first directory up from the working one that has it. */
    static Path findDoc() {
        for (Path dir = Paths.get("").toAbsolutePath(); dir != null; dir = dir.getParent()) {
            Path doc = dir.resolve("docs").resolve("DEBUG_FLAGS.md");
            if (Files.isRegularFile(doc)) return doc;
        }
        throw new IllegalStateException("no docs/DEBUG_FLAGS.md above " + Paths.get("").toAbsolutePath());
    }
}
